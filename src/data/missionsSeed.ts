// Helper to create 3 activities corresponding to 3 Assessment Levels (Thông tư 27)
function createThreeLevelActivities(
  stopId: string,
  level1Prompt: string,
  level1Options: { id: string; label: string; isCorrect: boolean }[],
  level1CorrectId: string,
  level1Feedback: { correct: string; wrong: string; hint: string },
  level2Prompt: string,
  level2Options: { id: string; label: string; isCorrect: boolean }[],
  level2CorrectId: string,
  level2Feedback: { correct: string; wrong: string; hint: string },
  level3Prompt: string,
  level3Options: { id: string; label: string; isCorrect: boolean }[],
  level3CorrectId: string,
  level3Feedback: { correct: string; wrong: string; hint: string }
): Activity[] {
  return [
    {
      id: `${stopId}-act-1`,
      stageId: stopId,
      type: 'single_choice',
      difficulty: 'basic',
      assessmentLevel: 1, // Mức 1: Nhận biết
      prompt: level1Prompt,
      options: level1Options,
      correctAnswer: level1CorrectId,
      score: 10,
      feedbackCorrect: level1Feedback.correct,
      feedbackWrong: level1Feedback.wrong,
      ritaHint: level1Feedback.hint,
      verified: true,
      required: true,
    },
    {
      id: `${stopId}-act-2`,
      stageId: stopId,
      type: 'single_choice',
      difficulty: 'applied',
      assessmentLevel: 2, // Mức 2: Thông hiểu
      prompt: level2Prompt,
      options: level2Options,
      correctAnswer: level2CorrectId,
      score: 10,
      feedbackCorrect: level2Feedback.correct,
      feedbackWrong: level2Feedback.wrong,
      ritaHint: level2Feedback.hint,
      verified: true,
      required: true,
    },
    {
      id: `${stopId}-act-3`,
      stageId: stopId,
      type: 'single_choice',
      difficulty: 'challenge',
      assessmentLevel: 3, // Mức 3: Vận dụng
      prompt: level3Prompt,
      options: level3Options,
      correctAnswer: level3CorrectId,
      score: 10,
      feedbackCorrect: level3Feedback.correct,
      feedbackWrong: level3Feedback.wrong,
      ritaHint: level3Feedback.hint,
      verified: true,
      required: true,
    },
  ];
}

